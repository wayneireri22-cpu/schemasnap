function joinWaitlist(e) {
  e.preventDefault();
  const email = document.getElementById('waitlist-email').value;
  // Store locally for now
  const waitlist = JSON.parse(localStorage.getItem('schemasnap_waitlist') || '[]');
  if (!waitlist.includes(email)) {
    waitlist.push(email);
    localStorage.setItem('schemasnap_waitlist', JSON.stringify(waitlist));
  }
  showToast(`📝 You're on the list! We'll notify ${email} when Pro launches.`);
  document.getElementById('waitlist-email').value = '';
}

function showToast(msg) {
  const existing = document.querySelector('.toast');
  if (existing) existing.remove();
  
  const toast = document.createElement('div');
  toast.className = 'toast';
  toast.textContent = msg;
  document.body.appendChild(toast);
  
  requestAnimationFrame(() => toast.classList.add('show'));
  setTimeout(() => {
    toast.classList.remove('show');
    setTimeout(() => toast.remove(), 300);
  }, 2500);
}

// ============================================================
// Utility functions
// ============================================================

function capitalize(str) {
  return str.charAt(0).toUpperCase() + str.slice(1).replace(/[^a-zA-Z0-9]/g, '');
}

function snakeCase(str) {
  return str.replace(/[^a-zA-Z0-9]/g, '_');
}

