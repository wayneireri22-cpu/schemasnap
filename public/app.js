// SchemaSnap — Core Application
// JSON → TypeScript, Zod, JSON Schema converter
// Everything runs client-side. No data is sent to any server.

let currentFormat = 'typescript';
const MAX_FREE_SIZE = 50 * 1024; // 50KB

// ============================================================
// Format Switching
// ============================================================

function switchFormat(format) {
  currentFormat = format;
  document.querySelectorAll('.tab').forEach(t => t.classList.remove('active'));
  document.querySelector(`[data-format="${format}"]`).classList.add('active');
  
  const labels = { typescript: 'TypeScript Interfaces', zod: 'Zod Schema', jsonschema: 'JSON Schema' };
  document.getElementById('output-label').textContent = labels[format];
  
  const input = document.getElementById('json-input').value.trim();
  if (input) convert(input);
}

// ============================================================
// Conversion Engine
// ============================================================

function convert(jsonStr) {
  const output = document.getElementById('json-output');
  const sizeIndicator = document.getElementById('size-indicator');
  
  try {
    const size = new Blob([jsonStr]).size;
    sizeIndicator.textContent = (size / 1024).toFixed(1) + ' KB';
    
    if (size > MAX_FREE_SIZE) {
      output.textContent = `// ⚠️ Input is ${(size / 1024).toFixed(1)}KB\n// Free tier supports up to 50KB\n// Upgrade to Pro for unlimited size.`;
      output.className = 'output error';
      return;
    }
    
    const parsed = JSON.parse(jsonStr);
    
    let result;
    switch (currentFormat) {
      case 'typescript': result = toTypeScript(parsed); break;
      case 'zod': result = toZod(parsed); break;
      case 'jsonschema': result = toJSONSchema(parsed); break;
    }
    
    output.textContent = result;
    output.className = 'output';
    
  } catch (e) {
    output.textContent = `// ❌ Error: ${e.message}`;
    output.className = 'output error';
  }
}

// ============================================================
// JSON → TypeScript
// ============================================================

function toTypeScript(obj, name = 'Root') {
  return `// Generated by SchemaSnap\n// Paste this into your TypeScript project\n\n${generateTypeScriptType(obj, name, new Set())}`;
}

function getTypeScriptType(value, inferredName, seen) {
  if (value === null) return 'null';
  if (value === undefined) return 'undefined';
  
  const type = typeof value;
  
  switch (type) {
    case 'string': return 'string';
    case 'number': return 'number';
    case 'boolean': return 'boolean';
    case 'object':
      if (Array.isArray(value)) {
        if (value.length === 0) return 'unknown[]';
        const elementTypes = [...new Set(value.map(v => getTypeScriptType(v, inferredName + 'Item', seen)))];
        if (elementTypes.length === 1) return `${elementTypes[0]}[]`;
        return `(${elementTypes.join(' | ')})[]`;
      }
      return generateTypeScriptType(value, inferredName, seen);
  }
  return 'any';
}

function generateTypeScriptType(obj, name, seen) {
  if (seen.has(obj)) return name;
  seen.add(obj);
  
  const keys = Object.keys(obj);
  if (keys.length === 0) return 'Record<string, unknown>';
  
  const props = keys.map(key => {
    const val = obj[key];
    const tsType = getTypeScriptType(val, capitalize(key), seen);
    const optional = val === null || val === undefined ? '?' : '';
    const formattedKey = /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(key) ? key : `'${key}'`;
    return `  ${formattedKey}${optional}: ${tsType};`;
  });
  
  return `interface ${name} {\n${props.join('\n')}\n}`;
}

// ============================================================
// JSON → Zod Schema
// ============================================================

function toZod(obj, name = 'rootSchema') {
  return `// Generated by SchemaSnap\n// Requires: npm install zod\n\nimport { z } from 'zod';\n\nexport const ${name} = ${generateZodSchema(obj, 'rootSchema', new Set())};\n\nexport type ${capitalize(name)} = z.infer<typeof ${name}>;`;
}

function generateZodSchema(value, inferredName, seen) {
  if (value === null || value === undefined) return 'z.nullable(z.unknown())';
  
  const type = typeof value;
  
  switch (type) {
    case 'string': return 'z.string()';
    case 'number': return 'z.number()';
    case 'boolean': return 'z.boolean()';
    case 'object':
      if (Array.isArray(value)) {
        if (value.length === 0) return 'z.array(z.unknown())';
        const elementTypes = [...new Set(value.map(v => generateZodSchema(v, inferredName + 'Item', seen)))];
        if (elementTypes.length === 1) return `z.array(${elementTypes[0]})`;
        return `z.array(z.union([${elementTypes.join(', ')}]))`;
      }
      
      if (seen.has(value)) return `z.lazy(() => ${inferredName})`;
      seen.add(value);
      
      const keys = Object.keys(value);
      if (keys.length === 0) return 'z.record(z.unknown())';
      
      const shape = keys.map(key => {
        const val = value[key];
        const zodType = generateZodSchema(val, snakeCase(key), seen);
        return `    ${key}: ${zodType},`;
      });
      
      return `z.object({\n${shape.join('\n')}\n  })`;
  }
  
  return 'z.unknown()';
}

// ============================================================
// JSON → JSON Schema
// ============================================================

function toJSONSchema(obj) {
  const schema = generateJSONSchema(obj, new Set());
  return JSON.stringify(schema, null, 2);
}

function generateJSONSchema(value, seen) {
  if (value === null || value === undefined) {
    return { type: 'null' };
  }
  
  const type = typeof value;
  
  switch (type) {
    case 'string':
      return { type: 'string' };
    case 'number':
      return { type: 'number' };
    case 'boolean':
      return { type: 'boolean' };
    case 'object':
      if (Array.isArray(value)) {
        if (value.length === 0) return { type: 'array', items: {} };
        const itemSchemas = value.map(v => generateJSONSchema(v, seen));
        const merged = mergeSchemas(itemSchemas);
        return {
          type: 'array',
          items: merged,
          minItems: value.length
        };
      }
      
      if (seen.has(value)) return {};
      seen.add(value);
      
      const keys = Object.keys(value);
      if (keys.length === 0) return { type: 'object', properties: {} };
      
      const properties = {};
      const required = [];
      
      keys.forEach(key => {
        properties[key] = generateJSONSchema(value[key], seen);
        if (value[key] !== null && value[key] !== undefined) {
          if (!required.includes(key)) required.push(key);
        }
      });
      
      const result = {
        type: 'object',
        properties,
        additionalProperties: false
      };
      
      if (required.length > 0) result.required = required;
      
      return result;
  }
  
  return {};
}

function mergeSchemas(schemas) {
  if (schemas.length === 0) return {};
  if (schemas.length === 1) return schemas[0];
  
  const types = [...new Set(schemas.map(s => s.type))];
  
  // If all same type, merge properties
  if (types.length === 1) {
    if (types[0] !== 'object') return { type: types[0] };
    
    const allProps = {};
    const allRequired = [];
    
    schemas.forEach(s => {
      if (s.properties) Object.assign(allProps, s.properties);
      if (s.required) allRequired.push(...s.required);
    });
    
    return {
      type: 'object',
      properties: allProps,
      ...(allRequired.length > 0 ? { required: [...new Set(allRequired)] } : {})
    };
  }
  
  return { anyOf: schemas };
}

