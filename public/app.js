document.addEventListener('DOMContentLoaded', () => {
  const input = document.getElementById('json-input');
  let debounceTimer;
  
  input.addEventListener('input', () => {
    clearTimeout(debounceTimer);
    debounceTimer = setTimeout(() => {
      const val = input.value.trim();
      if (val) convert(val);
    }, 300);
  });
  
  // Handle paste events
  input.addEventListener('paste', () => {
    setTimeout(() => {
      const val = input.value.trim();
      if (val) convert(val);
    }, 100);
  });
});

// Auto-convert on format switch if input exists
const originalSwitchFormat = switchFormat;
switchFormat = function(format) {
  originalSwitchFormat(format);
  const input = document.getElementById('json-input').value.trim();
  if (input && !input.includes('Paste your JSON')) {
    convert(input);
  }
};

function formatJSON() {
  const input = document.getElementById('json-input');
  try {
    const formatted = JSON.stringify(JSON.parse(input.value), null, 2);
    input.value = formatted;
    convert(formatted);
  } catch (e) {
    showToast('Invalid JSON — cannot format');
  }
}

function clearInput() {
  document.getElementById('json-input').value = '';
  document.getElementById('json-output').textContent = '// Your types will appear here\n// Just paste JSON on the left ↗';
  document.getElementById('json-output').className = 'output';
  document.getElementById('size-indicator').textContent = '0 KB';
}

async function copyOutput() {
  const text = document.getElementById('json-output').textContent;
  try {
    await navigator.clipboard.writeText(text);
    showToast('Copied to clipboard!');
  } catch {
    // Fallback
    const textarea = document.createElement('textarea');
    textarea.value = text;
    document.body.appendChild(textarea);
    textarea.select();
    document.execCommand('copy');
    document.body.removeChild(textarea);
    showToast('Copied!');
  }
}

